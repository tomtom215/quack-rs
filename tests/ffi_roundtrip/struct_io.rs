// ─── Checking a copy ─────────────────────────────────────────────────────────

/// Runs `function` over `n` generated rows and checks the output against the
/// input, field by field, with `DuckDB` doing the comparison — and against the
/// Rust model of where the NULLs are, so a copy that dropped every value (or
/// every NULL) on both sides cannot pass by agreeing with itself.
fn check_copy(fx: &Fixture, function: &str, n: usize) {
    let input = input_sql(n);
    let want_null_structs = (0..n).filter(|&i| struct_is_null(i)).count();

    // Field by field, so a failure names the field.
    let compare = FIELDS
        .iter()
        .map(|f| {
            format!(
                "(count(*) FILTER (WHERE g.{n} IS DISTINCT FROM s.{n}))::VARCHAR, \
                 (count(*) FILTER (WHERE g.{n} IS NOT NULL))::VARCHAR",
                n = f.name
            )
        })
        .collect::<Vec<_>>()
        .join(", ");
    let sql = format!(
        "WITH t AS (SELECT s, {function}(s) AS g FROM ({input})) \
         SELECT count(*)::VARCHAR, \
                (count(*) FILTER (WHERE g IS DISTINCT FROM s))::VARCHAR, \
                (count(*) FILTER (WHERE g IS NULL))::VARCHAR, {compare} FROM t"
    );
    let rows = text_rows(fx, &sql);
    let row = rows[0]
        .iter()
        .map(|c| c.as_deref().expect("counts are never NULL"))
        .collect::<Vec<_>>();
    assert_eq!(row[0], n.to_string(), "{function}: row count");
    assert_eq!(row[1], "0", "{function} n={n}: whole struct differs");
    assert_eq!(
        row[2],
        want_null_structs.to_string(),
        "{function} n={n}: NULL structs"
    );
    for (k, f) in FIELDS.iter().enumerate() {
        assert_eq!(
            row[3 + 2 * k],
            "0",
            "{function} n={n}: field `{}` differs from the input",
            f.name
        );
        let want_non_null = (0..n)
            .filter(|&i| !struct_is_null(i) && !field_is_null(i, k))
            .count();
        assert_eq!(
            row[4 + 2 * k],
            want_non_null.to_string(),
            "{function} n={n}: non-NULL values of field `{}`",
            f.name
        );
    }

    // The same, rendered, row by row.
    let sql = format!("SELECT {function}(s)::VARCHAR, s::VARCHAR FROM ({input}) ORDER BY i");
    let rows = text_rows(fx, &sql);
    assert_eq!(rows.len(), n);
    for (i, row) in rows.iter().enumerate() {
        assert_eq!(row[0], row[1], "{function} n={n} row {i}");
        assert_eq!(row[0].is_none(), struct_is_null(i), "row {i}");
    }
}

#[test]
fn struct_reader_reads_every_field_type() {
    let fx = Fixture::open();
    register(&fx, "struct_reader_to_raw", struct_reader_to_raw);
    for n in edge_rows() {
        check_copy(&fx, "struct_reader_to_raw", n);
    }
    // Two full chunks and a partial third.
    check_copy(&fx, "struct_reader_to_raw", 4100);
}

#[test]
fn struct_writer_writes_every_field_type() {
    let fx = Fixture::open();
    register(&fx, "raw_to_struct_writer", raw_to_struct_writer);
    for n in edge_rows() {
        check_copy(&fx, "raw_to_struct_writer", n);
    }
    check_copy(&fx, "raw_to_struct_writer", 4100);
}

#[test]
