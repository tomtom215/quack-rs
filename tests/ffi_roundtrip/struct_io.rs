//! `StructReader` and `StructWriter`, every typed method of both, against a
//! live `DuckDB`.
//!
//! One STRUCT with twenty fields — one per physical layout the two types name
//! — goes in as scalar-function input, and comes back out as a STRUCT. Three
//! functions pin down which side is at fault when a round trip breaks:
//!
//! - `StructReader` -> plain `VectorWriter`s on the output's field vectors
//!   (the reader is under test; the writer is the one the echo tests prove),
//! - plain `VectorReader`s on the input's field vectors -> `StructWriter`
//!   (the writer is under test),
//! - `StructReader` -> `StructWriter` (both, plus `is_valid`, `field`,
//!   `field_count` and `set_row_null`).
//!
//! The input is generated by SQL, so the expected value of every field in
//! every row is `DuckDB`'s own. Every field is NULL in some rows, one row in
//! thirteen has all fields NULL inside a valid struct, and one row in seven is
//! a NULL struct. The row counts sit on both sides of the vector size.

