//! Templates for the generated GitHub Actions workflows.
//!
//! Two workflows, as in `duckdb/extension-template-rs`:
//!
//! - `extension-ci.yml` — fast native feedback: `cargo fmt`, `clippy` and unit
//!   tests, the extension-ci-tools `make configure / release / test` path on
//!   three platforms, and a build on the minimum supported Rust version.
//! - `MainDistributionPipeline.yml` — calls extension-ci-tools'
//!   `_extension_distribution.yml`, the same reusable workflow the community
//!   extensions repository builds with, for every platform `description.yml`
//!   does not exclude.
//!
//! Templates are plain strings with `@@KEY@@` placeholders, so the
//! `${{ ... }}` GitHub expressions in them need no brace escaping.

use super::ScaffoldConfig;

/// `actions/checkout` v7.0.1.
const CHECKOUT: &str = "actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1";
/// `dtolnay/rust-toolchain`: the action publishes no release tags for its
/// `master` branch, whose `toolchain:` input is required.
const RUST_TOOLCHAIN: &str =
    "dtolnay/rust-toolchain@e2a55d2ffb04f378e9626c28d38b36d230d1e12f # master 2026-10-08";
/// `Swatinem/rust-cache` v2.9.2.
const RUST_CACHE: &str = "Swatinem/rust-cache@6323deb102c322ba6fcbdcafc7e3dddab59af2b6 # v2.9.2";
/// `actions/setup-python` v7.0.0 (node24).
const SETUP_PYTHON: &str = "actions/setup-python@5fda3b95a4ea91299a34e894583c3862153e4b97 # v7.0.0";

const EXTENSION_CI: &str = r"# GitHub Actions CI for the @@NAME@@ DuckDB extension.
# Generated by the quack-rs scaffold — customize as needed.
#
# Fast native checks. The build for every platform the community repository
# ships (linux, macOS, Windows, wasm) is MainDistributionPipeline.yml.
#
# The build goes through extension-ci-tools' Makefiles (see ./Makefile), which
# need the git submodule and a Python 3 virtualenv. `make configure` creates the
# venv, writes configure/platform.txt and resolves the extension version;
# `make release` builds the cdylib and appends the DuckDB extension metadata
# footer; `make test` runs the SQLLogicTests in test/sql against a real DuckDB
# with the extension loaded.

name: Extension CI

on:
  push:
    branches: [main]
  pull_request:
    branches: [main]

env:
  CARGO_TERM_COLOR: always

jobs:
  build:
    name: Build and test (${{ matrix.platform }})
    strategy:
      fail-fast: false
      matrix:
        include:
          - os: ubuntu-latest
            platform: linux_amd64
          - os: macos-latest
            platform: osx_arm64
          - os: windows-latest
            platform: windows_amd64
    runs-on: ${{ matrix.os }}
    env:
      # Empty on Linux, so extension-ci-tools detects the platform itself:
      # its base.Makefile sets SKIP_TESTS=1 whenever DUCKDB_PLATFORM is
      # linux_amd64, which would turn the SQLLogicTest step into a no-op.
      DUCKDB_PLATFORM: ${{ matrix.os != 'ubuntu-latest' && matrix.platform || '' }}
    steps:
      # Every action is SHA-pinned. A tag or branch is a moving target that the
      # action's owner can repoint at any time, and a workflow step runs
      # arbitrary code in your CI.
      - uses: @@CHECKOUT@@
        with:
          submodules: recursive

      # Pinning the action does not pin your Rust version: `toolchain: stable`
      # installs the current stable release on every run.
      - uses: @@RUST_TOOLCHAIN@@
        with:
          toolchain: stable
          components: clippy, rustfmt

      - uses: @@RUST_CACHE@@

      - uses: @@SETUP_PYTHON@@
        with:
          python-version: '3.12'

      - name: Lint
        if: matrix.os == 'ubuntu-latest'
        run: |
          cargo fmt -- --check
          cargo clippy --all-targets -- -D warnings

      - name: Unit tests
        run: cargo test

      - name: Configure (venv, platform, version)
        run: make configure

      - name: Build extension with metadata
        run: make release

      - name: SQLLogicTest (end to end)
        run: make test

  msrv:
    # The oldest Rust the project promises to build with: `rust-version` in
    # Cargo.toml. extension-ci-tools builds the wasm targets with this same
    # release. Keep the two in step.
    name: Minimum supported Rust (@@MSRV@@)
    runs-on: ubuntu-latest
    steps:
      - uses: @@CHECKOUT@@

      - uses: @@RUST_TOOLCHAIN@@
        with:
          toolchain: '@@MSRV@@'

      - uses: @@RUST_CACHE@@

      - name: Build and test on the minimum supported Rust
        run: |
          cargo build --release
          cargo test
";

const DISTRIBUTION: &str = r"# Builds the @@NAME@@ extension for every DuckDB platform with
# extension-ci-tools' reusable workflow -- the same one the community
# extensions repository uses -- so a platform that fails here would fail there.
# Generated by the quack-rs scaffold; mirrors duckdb/extension-template-rs.
#
# `duckdb_version` and `ci_tools_version` name an extension-ci-tools branch
# (one exists for every DuckDB release); keep them equal to the branch the
# extension-ci-tools submodule tracks (.gitmodules).
#
# `exclude_archs` must list the same platforms as `excluded_platforms` in
# description.yml. To opt a platform in, remove it from both.
name: Main Extension Distribution Pipeline
on:
  push:
    branches: [main]
  pull_request:
  workflow_dispatch:

concurrency:
  group: ${{ github.workflow }}-${{ github.ref }}-${{ github.head_ref || '' }}-${{ github.base_ref || '' }}-${{ github.ref != 'refs/heads/main' || github.sha }}
  cancel-in-progress: true

jobs:
  duckdb-stable-build:
    name: Build extension binaries
    uses: duckdb/extension-ci-tools/.github/workflows/_extension_distribution.yml@@@CI_TOOLS_REF@@
    with:
      duckdb_version: @@CI_TOOLS_REF@@
      ci_tools_version: @@CI_TOOLS_REF@@
      extension_name: @@NAME@@
      extra_toolchains: rust;python3
      exclude_archs: '@@EXCLUDE_ARCHS@@'
";

fn fill(template: &str, config: &ScaffoldConfig) -> String {
    template
        .replace("@@NAME@@", &config.name)
        .replace("@@CHECKOUT@@", CHECKOUT)
        .replace("@@RUST_TOOLCHAIN@@", RUST_TOOLCHAIN)
        .replace("@@RUST_CACHE@@", RUST_CACHE)
        .replace("@@SETUP_PYTHON@@", SETUP_PYTHON)
        .replace("@@MSRV@@", env!("CARGO_PKG_RUST_VERSION"))
        .replace("@@CI_TOOLS_REF@@", super::extension_ci_tools_ref(config))
        .replace("@@EXCLUDE_ARCHS@@", &config.excluded_platforms.join(";"))
}

/// `.github/workflows/extension-ci.yml`: native lint, unit tests, the
/// extension-ci-tools build and `SQLLogicTest` on three platforms, and an MSRV
/// build.
pub(super) fn generate_extension_ci(config: &ScaffoldConfig) -> String {
    fill(EXTENSION_CI, config)
}

/// `.github/workflows/MainDistributionPipeline.yml`: every community platform,
/// through extension-ci-tools' `_extension_distribution.yml`.
pub(super) fn generate_distribution_workflow(config: &ScaffoldConfig) -> String {
    fill(DISTRIBUTION, config)
}
